/**
 * Chat History Utility
 * 
 * Manages chat conversation history stored in Supabase.
 */

import { supabase } from './supabase';

// ============================================================================
// TYPES
// ============================================================================

export interface ChatMessage {
    id: string;
    conversation_id: string;
    role: 'user' | 'assistant';
    content: string;
    metadata?: {
        workout_data?: any;
        workoutData?: any;
    };
    created_at: string;
}

export interface Conversation {
    id: string;
    user_id: string;
    title?: string;
    created_at: string;
    updated_at: string;
}

/**
 * Conversation summary for list display
 */
export interface ConversationSummary {
    conversation_id: string;
    /** Auto-generated by the backend after the first turn; falls back to first_user_message in UI. */
    title?: string | null;
    first_user_message?: string;
    last_message_at: string;
    message_count: number;
}

// ============================================================================
// CONVERSATION ID GENERATION
// ============================================================================

/**
 * Generate a UUID v4 for conversation ID
 * Database expects proper UUID format
 */
export function generateConversationId(): string {
    return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, function (c) {
        const r = Math.random() * 16 | 0;
        const v = c === 'x' ? r : (r & 0x3 | 0x8);
        return v.toString(16);
    });
}

// ============================================================================
// SAVE MESSAGE
// ============================================================================

export async function saveMessage(
    userId: string,
    conversationId: string,
    role: 'user' | 'assistant',
    content: string,
    metadata?: any
): Promise<{ success: boolean; error?: string }> {
    try {
        // Ensure the conversation row exists. Upsert instead of select-then-insert
        // so two racing saves (user message + assistant reply) can't both miss
        // the existence check and collide on the primary key.
        const { error: convError } = await supabase.from('chat_conversations').upsert(
            {
                id: conversationId,
                user_id: userId,
                updated_at: new Date().toISOString(),
            },
            { onConflict: 'id' }
        );

        if (convError) {
            console.error('Error ensuring conversation:', convError);
            return { success: false, error: convError.message };
        }

        const { error } = await supabase.from('chat_messages').insert({
            conversation_id: conversationId,
            user_id: userId,
            role,
            content,
            metadata: metadata || {},
            created_at: new Date().toISOString(),
        });

        if (error) {
            console.error('Error saving message:', error);
            return { success: false, error: error.message };
        }

        return { success: true };
    } catch (error) {
        console.error('Error in saveMessage:', error);
        return { success: false, error: String(error) };
    }
}

// ============================================================================
// LOAD CONVERSATION
// ============================================================================

export async function loadConversation(conversationId: string): Promise<{
    conversation?: Conversation;
    messages: ChatMessage[];
    error?: string;
}> {
    try {
        // Get conversation
        const { data: conversation, error: convError } = await supabase
            .from('chat_conversations')
            .select('*')
            .eq('id', conversationId)
            .single();

        if (convError) {
            return { messages: [], error: convError.message };
        }

        // Get messages
        const { data: messages, error: msgError } = await supabase
            .from('chat_messages')
            .select('*')
            .eq('conversation_id', conversationId)
            .order('created_at', { ascending: true });

        if (msgError) {
            return { messages: [], error: msgError.message };
        }

        return {
            conversation: conversation as Conversation,
            messages: (messages || []) as ChatMessage[],
        };
    } catch (error) {
        console.error('Error loading conversation:', error);
        return { messages: [], error: String(error) };
    }
}

// ============================================================================
// LIST CONVERSATIONS
// ============================================================================

export async function listConversations(userId: string): Promise<{
    conversations: Conversation[];
    error?: string;
}> {
    try {
        const { data, error } = await supabase
            .from('chat_conversations')
            .select('*')
            .eq('user_id', userId)
            .order('updated_at', { ascending: false })
            .limit(50);

        if (error) {
            return { conversations: [], error: error.message };
        }

        return { conversations: (data || []) as Conversation[] };
    } catch (error) {
        console.error('Error listing conversations:', error);
        return { conversations: [], error: String(error) };
    }
}

/**
 * Get conversation list with summaries for sidebar display
 * Uses the conversation_summaries view from Supabase
 */
export async function getConversationList(userId: string): Promise<{
    conversations: ConversationSummary[];
    error?: string;
}> {
    try {
        const { data, error } = await supabase
            .from('conversation_summaries')
            .select('*')
            .eq('user_id', userId)
            .order('last_message_at', { ascending: false })
            .limit(50);

        if (error) {
            // If view doesn't exist, return empty list
            console.warn('Conversation summaries view not available:', error.message);
            return { conversations: [] };
        }

        const summaries: ConversationSummary[] = (data || []).map((row: any) => ({
            conversation_id: row.conversation_id || row.id,
            title: typeof row.title === 'string' ? row.title : null,
            first_user_message: row.first_user_message,
            last_message_at: row.last_message_at || row.updated_at,
            message_count: row.message_count || 0,
        }));

        // The summaries view predates auto-titles and may not expose the
        // title column — merge titles from chat_conversations when missing.
        if (summaries.length > 0 && summaries.every(s => !s.title)) {
            const ids = summaries.map(s => s.conversation_id);
            const { data: titleRows } = await supabase
                .from('chat_conversations')
                .select('id, title')
                .in('id', ids);
            if (titleRows?.length) {
                const titleById = new Map(
                    titleRows.map((r: any) => [r.id as string, r.title as string | null])
                );
                for (const s of summaries) {
                    s.title = titleById.get(s.conversation_id) ?? null;
                }
            }
        }

        return { conversations: summaries };
    } catch (error) {
        console.error('Error getting conversation list:', error);
        return { conversations: [], error: String(error) };
    }
}

// ============================================================================
// DELETE CONVERSATION
// ============================================================================

export async function deleteConversation(conversationId: string): Promise<{
    success: boolean;
    error?: string;
}> {
    try {
        // Also delete the backend's LangGraph thread (conversation_state) so
        // the server-side chat memory doesn't outlive the conversation.
        // Best-effort: a network failure here must not block the local delete.
        try {
            const { backendClient } = await import('../src/api/backendClient');
            await backendClient.deleteChatThread(conversationId);
        } catch (err) {
            console.warn('Backend thread delete failed (non-fatal):', err);
        }

        // Delete messages first
        await supabase
            .from('chat_messages')
            .delete()
            .eq('conversation_id', conversationId);

        // Delete conversation
        const { error } = await supabase
            .from('chat_conversations')
            .delete()
            .eq('id', conversationId);

        if (error) {
            return { success: false, error: error.message };
        }

        return { success: true };
    } catch (error) {
        console.error('Error deleting conversation:', error);
        return { success: false, error: String(error) };
    }
}
